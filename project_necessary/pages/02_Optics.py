import streamlit as st
import numpy as np
import plotly.graph_objects as go

# заголовок окна и разметку задаёт main.py — здесь вызывать нельзя
st.title("Оптический симулятор")


def render_refraction():
    """Преломление, полное внутреннее отражение — исходный раздел страницы."""
    c_ctrl, c_plot, c_math = st.columns([1, 2.2, 1.2])

    # --- 1. НАСТРОЙКИ ---
    with c_ctrl:
        st.header("Параметры")
        # Ключи нужны проверке checks/verify_refraction.py: по ним она подставляет
        # значения ползунков, когда исполняет страницу без браузера.
        n1 = st.slider("n1 (Верх)", 1.0, 2.5, 1.5, key="refr_n1")
        n2 = st.slider("n2 (Низ)", 1.0, 2.5, 1.0, key="refr_n2")

        # Выбор стороны и четверти
        side = st.radio("Сторона источника:", ["Слева", "Справа"], key="refr_side")
        vert = st.radio("Вертикаль:", ["Сверху", "Снизу"], key="refr_vert")
        angle_deg = st.slider("Угол падения α (0-90°)", 0, 90, 30, key="refr_angle")

    # Верхняя среда — всегда n1, нижняя — всегда n2. «Вертикаль» говорит лишь о
    # том, откуда луч идёт: start_n — среда, в которой он сейчас, end_n — та,
    # куда он пытается выйти.
    start_n, end_n = (n1, n2) if vert == "Сверху" else (n2, n1)
    y_dir = 1 if vert == "Сверху" else -1
    x_side = -1 if side == "Слева" else 1

    # --- 2. ВЫЧИСЛЕНИЯ (один расчёт на весь раздел) ---
    # Закон Снеллиуса: start_n * sin(α) = end_n * sin(β). Если sin(β) выходит за
    # единицу, преломления нет — полное внутреннее отражение. Крайние углы 0° и
    # 90° считаются той же формулой: отдельных случаев для них быть не должно,
    # иначе рисунок расходится с физикой.
    alpha_rad = np.radians(angle_deg)
    sin_beta = (start_n * np.sin(alpha_rad)) / end_n

    if sin_beta > 1.0:
        total_reflection = True
        beta_rad = alpha_rad            # при отражении угол выхода равен углу падения
        beam_label, beam_color = "ПВО", "red"
    else:
        total_reflection = False
        beta_rad = np.arcsin(sin_beta)
        beam_label, beam_color = "Преломление", "#00ff9d"
    beta_deg = np.degrees(beta_rad)

    # --- 3. КООРДИНАТЫ ---
    # Падающий луч
    x_inc = [x_side * np.sin(alpha_rad), 0]
    y_inc = [y_dir * np.cos(alpha_rad), 0]

    # Выходящий луч
    if total_reflection:
        # ПОЛНОЕ ОТРАЖЕНИЕ: 
        # y_refr остается с тем же знаком, что и y_dir (та же среда)
        # x_refr меняет знак (отскакивает в другую сторону)
        # beta_rad при ПВО равен alpha_rad (угол падения = углу отражения)
        x_refr = [0, -x_side * np.sin(alpha_rad)] 
        y_refr = [0, y_dir * np.cos(alpha_rad)]
    else:
        # ПРЕЛОМЛЕНИЕ:
        # Уходит в противоположную среду (-y_dir) 
        # И в противоположную сторону по горизонтали (-x_side)
        x_refr = [0, -x_side * np.sin(beta_rad)]
        y_refr = [0, -y_dir * np.cos(beta_rad)]

    # --- 4. ОТРИСОВКА ---
    def get_arc_path(start_deg, end_deg, radius=0.3):
        # Нормализация, чтобы дуга всегда была короткой (не более 180 градусов)
        diff = (end_deg - start_deg + 180) % 360 - 180
        end_deg = start_deg + diff
    
        t = np.linspace(np.radians(start_deg), np.radians(end_deg), 30)
        x = radius * np.cos(t)
        y = radius * np.sin(t)
    
        path = f"M {x[0]},{y[0]}"
        for xi, yi in zip(x[1:], y[1:]):
            path += f" L {xi},{yi}"
        return path

    fig = go.Figure()

    def arc_middle(start_deg, end_deg, radius=0.45):
        """Середина короткой дуги — туда ставим букву угла."""
        diff = (end_deg - start_deg + 180) % 360 - 180
        mid = np.radians(start_deg + diff / 2)
        return radius * np.cos(mid), radius * np.sin(mid)

    # --- ДУГА И БУКВА АЛЬФА (α) ---
    # Угол всегда считается от нормали (вертикальной линии) до луча.
    base_angle_alpha = 90 if vert == "Сверху" else 270
    arc_end_alpha = (base_angle_alpha - x_side * angle_deg if vert == "Сверху"
                     else base_angle_alpha + x_side * angle_deg)

    if angle_deg > 0:                       # при 0° дуга вырождается в точку
        fig.add_shape(type="path", path=get_arc_path(base_angle_alpha, arc_end_alpha, radius=0.3),
                      line=dict(color="orange", width=2))
        ax_t, ay_t = arc_middle(base_angle_alpha, arc_end_alpha)
        fig.add_annotation(x=ax_t, y=ay_t, text="<b>α</b>", showarrow=False,
                           font=dict(color="orange", size=16))

    # --- ДУГА И БУКВА БЕТА (β) ---
    # Рисуем только когда есть преломлённый луч и угол не нулевой.
    if not total_reflection and beta_deg > 0.5:
        b_start = 270 if y_refr[1] < 0 else 90
        b_end = np.degrees(np.arctan2(y_refr[1], x_refr[1]))
        fig.add_shape(type="path", path=get_arc_path(b_start, b_end, radius=0.3),
                      line=dict(color="#00ff9d", width=2))
        bx, by = arc_middle(b_start, b_end)
        fig.add_annotation(x=bx, y=by, text="<b>β</b>", showarrow=False,
                           font=dict(color="#00ff9d", size=16))

    # --- 5. ОСИ И ЛИНИИ ---
    fig.add_trace(go.Scatter(x=[-1.5, 1.5], y=[0, 0], mode='lines', line=dict(dash="dash", color="gray", width=2), showlegend=False))
    fig.add_trace(go.Scatter(x=[0, 0], y=[-1, 1], mode='lines', line=dict(color="gray", width=2), showlegend=False))

    # Подписи сред: помечаем ту, откуда идёт луч, чтобы рисунок читался сразу.
    # Пометка идёт второй строкой (<br>), иначе длинная подпись вылезает за кадр.
    top_note = "<br>отсюда луч" if vert == "Сверху" else ""
    bottom_note = "<br>отсюда луч" if vert == "Снизу" else ""
    fig.add_annotation(x=-1.2, y=0.5, text=f"Среда 1 (n1={n1}){top_note}",
                       showarrow=False, font=dict(color="lightblue"))
    fig.add_annotation(x=-1.2, y=-0.5, text=f"Среда 2 (n2={n2}){bottom_note}",
                       showarrow=False, font=dict(color="lightyellow"))

    # Отрисовка лучей
    fig.add_trace(go.Scatter(x=x_inc, y=y_inc, mode='lines', name="Падающий луч", line=dict(color="yellow", width=4)))
    fig.add_trace(go.Scatter(x=x_refr, y=y_refr, mode='lines', name=beam_label, line=dict(color=beam_color, width=4)))

    fig.update_layout(
        xaxis=dict(range=[-1.5, 1.5], showgrid=False, visible=False, fixedrange=True),
        yaxis=dict(range=[-1.2, 1.2], showgrid=False, visible=False, fixedrange=True),
        template="plotly_dark", height=500, margin=dict(t=20, b=20), showlegend=True
    )

    # --- 6. ВЫВОД СИМУЛЯЦИИ И МАТЕМАТИКА ---

    with c_plot:
        st.plotly_chart(fig, width="stretch", key="optics_final_v4")

    with c_math:
        st.subheader("Математика")
        # Формула пишется под выбранное направление: в числителе справа всегда
        # та среда, куда луч выходит, в знаменателе — откуда идёт.
        if vert == "Сверху":
            st.latex(r"\frac{\sin \alpha}{\sin \beta} = \frac{n_2}{n_1}")
        else:
            st.latex(r"\frac{\sin \alpha}{\sin \beta} = \frac{n_1}{n_2}")
        st.caption(f"Луч идёт из среды с n = {start_n} в среду с n = {end_n}.")

        # Критический угол есть только при переходе в менее плотную среду
        if start_n > end_n:
            critical_angle = np.degrees(np.arcsin(end_n / start_n))
            st.info(f"Критический угол: {critical_angle:.2f}°")

        # Все величины берём из общего расчёта выше — отдельного счёта здесь нет,
        # поэтому метрика и рисунок разойтись не могут.
        if total_reflection:
            st.error("⚠️ Полное отражение")
            st.metric("Угол преломления β", "Нет (ПВО)")
            st.caption("Угол падения больше критического: луч не выходит наружу, "
                       "а целиком отражается обратно в свою среду.")
        elif angle_deg == 0:
            st.success("✅ Падение по нормали (0°)")
            st.metric("Угол преломления β", "0.00°")
            st.caption("Луч идёт перпендикулярно границе и проходит насквозь, "
                       "не меняя направления.")
        elif angle_deg == 90:
            st.success("✅ Скользящее падение (90°)")
            st.metric("Угол преломления β", f"{beta_deg:.2f}°")
            st.caption("Луч идёт вдоль самой границы — предельный случай. "
                       "Угол преломления при этом наибольший из возможных.")
        else:
            st.success("✅ Преломление")
            st.metric("Угол преломления β", f"{beta_deg:.2f}°")





    # --- 5. ТЕОРЕТИЧЕСКИЙ БЛОК (СОВМЕЩЕНИЕ) ---
    st.divider()
    st.header("📚 Справочные материалы")

    t_col1, t_col2 = st.columns(2)

    with t_col1:
        with st.expander("🤔 Почему свет преломляется?", expanded=True):
            st.write("""
            Преломление происходит из-за **изменения скорости света** при переходе из одной среды в другую. (это пример с абсолютным показателем, а с относительным это закон Снеллиуса)
            """)
            st.latex(r"n = \frac{c}{v}")
            st.caption("Где c — скорость света в вакууме, v — в среде.")

    with t_col2:
        with st.expander("📖 Основные определения", expanded=True):
            st.write("""
            - **Нормаль** — перпендикуляр к границе (на рисунке сплошная вертикальная линия, а сама граница сред — пунктирная).
            - **Коэффициент (показатель) преломления** (n) — это безразмерная величина, определяющая, во сколько раз скорость света в вакууме (c) выше скорости света в данной среде. (Это абсолютный коэффициент, а относительный это тоже самое, но с другими средами, не являющимися вакуумом)
            - **Угол падения (α)** — угол МЕЖДУ лучом и нормалью.
            - **Угол преломления (β)** — угол МЕЖДУ преломлённым лучом и нормалью
            - **Оптически более плотная среда** — среда с большим значением **n**.
            - **Принцип Ферма** - (физический смысл закона Снеллиуса) путь, который потребует минимум времени для прохождения между двумя точками. Чтобы сэкономить время в среде, где скорость ниже, свет сокращает путь в ней, «прижимаясь» к нормали.                     
            """)

    with st.expander("💡 Полное внутреннее отражение (ПВО)"):
        st.write("""
        Если свет идет из среды с большим **n** в среду с меньшим **n** (например, из стекла в воздух) под большим углом, он может не преломиться, а полностью отразиться назад.(так как наступает момент, когда sin(𝛽)по формуле должен стать больше 1.)
    
        **Где это используют?**
        - В **оптоволокне** (свет «прыгает» внутри кабеля, не выходя наружу).
        - В **алмазах** (именно из-за ПВО они так ярко блестят).
        """)

    # --- 6. ТЕСТ (Проверка знаний) ---
    st.subheader("📝 Мини-тест")
    answer = st.radio("Что произойдет с лучом, если он перейдет из воздуха (n=1) в стекло (n=1.5)?", 
                     ["Угол β станет больше угла α", "Угол β станет меньше угла α", "Луч не изменит направление"])
    if st.button("Проверить"):
        if answer == "Угол β станет меньше угла α":
            st.success("Правильно! В более плотной среде луч прижимается к нормали.")
        else:
            st.error("Неверно. Попробуй изменить n2 на 1.5 в симуляции и посмотри на график.")





def render_lenses():
    """Линзы: собирающая и рассеивающая, построение изображения предмета."""
    c_ctrl, c_plot, c_math = st.columns([1, 2.2, 1.2])

    with c_ctrl:
        st.subheader("Параметры")
        lens_kind = st.radio(
            "Тип линзы:",
            ["Собирающая (двояковыпуклая)", "Рассеивающая (двояковогнутая)"],
            key="lens_kind"
        )
        focal = st.slider("Фокусное расстояние |F|, см", 5, 30, 10, key="lens_focal")
        dist = st.slider("Расстояние до предмета d, см", 2, 60, 30, key="lens_dist")
        height = st.slider("Высота предмета h, см", 1, 10, 4, key="lens_height")

    # =====================================================================
    # РАСЧЁТ ПО ФОРМУЛЕ ТОНКОЙ ЛИНЗЫ
    # 1/F = 1/d + 1/f, откуда f = d*F / (d - F).
    # У собирающей линзы F > 0, у рассеивающей F < 0.
    # f > 0 — изображение действительное, за линзой; f < 0 — мнимое.
    # =====================================================================
    is_converging = lens_kind.startswith("Собирающая")
    F = float(focal) if is_converging else -float(focal)
    d = float(dist)
    h = float(height)

    denom = d - F
    no_image = abs(denom) < 1e-9          # предмет ровно в фокусе собирающей линзы
    if no_image:
        f_img = y_img = gamma = None
    else:
        f_img = d * F / denom             # расстояние от линзы до изображения
        y_img = -h * F / denom            # высота со знаком: минус — перевёрнутое
        gamma = abs(f_img) / d            # линейное увеличение

    # =====================================================================
    # МАСШТАБ СЦЕНЫ
    # =====================================================================
    span_candidates = [d, 2 * abs(F)]
    if f_img is not None and abs(f_img) < 6 * abs(F):
        span_candidates.append(abs(f_img))
    x_span = max(span_candidates) * 1.25
    image_off_screen = f_img is not None and abs(f_img) > x_span

    # Вертикальный масштаб НЕ подстраивается под высоту предмета: иначе при
    # движении ползунка h кадр растягивался бы вместе с предметом и на экране
    # ничего не менялось бы. Берём предел ползунка (10 см) с запасом, а кадр
    # расширяем только ради изображения, если оно выше предмета.
    y_span = max(11.0, h * 1.25)          # запас, чтобы линза была выше предмета
    if y_img is not None:
        # Третий (зелёный) луч пересекает линзу ровно на высоте изображения, так
        # что кадр тянем и под него — иначе при предмете у самого фокуса луч
        # уходил бы за край и казалось бы, что он обрывается. Коэффициент 1.32,
        # а не 1.15: над остриём стрелки должна поместиться ещё и подпись, иначе
        # у высокого изображения её срезает верхним краем.
        y_span = max(y_span, min(abs(y_img) * 1.32, 26.0))
    ray3_off_screen = y_img is not None and abs(y_img) > y_span

    def ray_to_edge(x0, y0, x1, y1, x_end):
        """Продолжает прямую через две точки до вертикали x_end."""
        if abs(x1 - x0) < 1e-12:
            return x_end, y1
        k = (y1 - y0) / (x1 - x0)
        return x_end, y1 + k * (x_end - x1)

    fig = go.Figure()

    # --- главная оптическая ось ---
    fig.add_trace(go.Scatter(x=[-x_span, x_span], y=[0, 0], mode="lines",
                             line=dict(color="gray", width=1.5), showlegend=False))

    # --- линза: у собирающей стрелки наружу, у рассеивающей внутрь ---
    lens_h = y_span * 0.82
    fig.add_trace(go.Scatter(x=[0, 0], y=[-lens_h, lens_h], mode="lines",
                             line=dict(color="#7fd4ff", width=4), showlegend=False))
    for tip_sign in (1, -1):
        y_out, y_in = tip_sign * lens_h, tip_sign * lens_h * 0.78
        if is_converging:
            tip_y, tail_y = y_out, y_in        # остриё наружу
        else:
            tip_y, tail_y = y_in, y_out        # остриё внутрь
        fig.add_annotation(x=0, y=tip_y, ax=0, ay=tail_y,
                           xref="x", yref="y", axref="x", ayref="y",
                           showarrow=True, arrowhead=2, arrowsize=1.4, arrowwidth=4,
                           arrowcolor="#7fd4ff")

    # --- фокусы и двойные фокусы с обеих сторон ---
    for sign in (1, -1):
        for mult, label in ((1, "F"), (2, "2F")):
            x_mark = sign * mult * abs(F)
            if abs(x_mark) > x_span:
                continue
            fig.add_trace(go.Scatter(x=[x_mark], y=[0], mode="markers",
                                     marker=dict(color="#9aa7b4", size=7), showlegend=False))
            fig.add_annotation(x=x_mark, y=-y_span * 0.12, text=label, showarrow=False,
                               font=dict(color="#9aa7b4", size=12))

    # --- предмет ---
    fig.add_shape(type="line", x0=-d, y0=0, x1=-d, y1=h,
                  xref="x", yref="y",
                  line=dict(color="gold", width=4))

    # 2. Невидимая стрелка-наконечник, которая просто рисует остриё на самой вершине (y=h)
    fig.add_annotation(x=-d, y=h, ax=-d, ay=0,
                       xref="x", yref="y", axref="x", ayref="y",
                       showarrow=True, arrowhead=3, arrowsize=0.6, arrowwidth=4,
                       arrowcolor="gold",
                       standoff=0,       # Убирает программный зазор у наконечника (сверху)
                       startstandoff=0)  # Убирает программный зазор у основания (снизу на оси)

    # Подпись держим внутри кадра (у высокого предмета она иначе уезжает за
    # верх) и прижимаем влево от стрелки: вправо от неё уходят все три луча,
    # и подпись над остриём они перечёркивают.
    # Рассчитываем позицию по Y чуть выше кончика стрелки предмета (h)
    y_obj_label = min(h + y_span * 0.09, y_span * 0.93)
    
    # Центрируем надпись прямо над стрелкой
    fig.add_annotation(x=-d, y=y_obj_label, 
                       text=f"<b>предмет</b><br>h = {h:.0f} см",
                       xanchor="center",  # Выравнивание по центру горизонтали
                       yanchor="bottom",  # Привязка нижней границы текста к y_obj_label
                       showarrow=False,
                       font=dict(color="gold", size=12))
                       
    # Предмет стоит на оси — отмечаем точку и расстояние до линзы
    fig.add_trace(go.Scatter(x=[-d], y=[0], mode="markers",
                             marker=dict(color="gold", size=5), showlegend=False))

    if h < 0:
        # Если предмет перевернут (уходит вниз), двигаем подпись чуть ниже его кончика
        y_d_label = h - (y_span * 0.07)
    else:
        # Если предмет идет вверх, то его низ — это ось. Ставим подпись чуть-чуть ниже оси
        y_d_label = -y_span * 0.08  
        
    # Защита от вылета за нижний край экрана (по высоте Y)
    y_d_label = max(-y_span * 0.93, y_d_label)   
    
    # ИСПРАВЛЕНО: xanchor="center" поставит текст ровно по центру оси предмета, без ухода влево
    fig.add_annotation(x=-d, y=y_d_label, text=f"d = {d:.0f} см",
                       xanchor="center", showarrow=False,
                       font=dict(color="gold", size=12))


    # =====================================================================
    # ТРИ ЛУЧА ПОСТРОЕНИЯ
    # 1. Параллельный оси — после линзы идёт по прямой через фокус F.
    # 2. Через оптический центр — не преломляется.
    # 3. Через передний фокус — после линзы параллелен оси.
