import streamlit as st

# Заголовок окна и разметка задаются один раз здесь — на всё приложение.
st.set_page_config(page_title="Физическая лаборатория", layout="wide")


def home():
    """Главная страница: что есть в лаборатории и куда идти дальше."""
    st.title("🔬 Виртуальная физическая лаборатория")
    st.markdown("""
    ### Добро пожаловать!
Выберите раздел в меню слева, чтобы начать эксперимент.

**Разделы:**
1.  **Механика** — нитяной маятник, бегущая волна, пружинный маятник.
2. **Оптика** — преломление с полным внутренним отражением, линзы и построение изображения.
3.  **Магнетизм** — взаимодействие магнитов, правила левой и правой руки, правило Ленца.

*Цель*: объяснить тяжёлые темы в физике 8-9 класс нагляднее.  
*Для кого*: Лаборатория для учеников 8-9 классов, людей, желающих изучить эти темы и/или вспомнить их для экзаменов.  
*Причина создания*: эти темы вызывают наибольшую сложность для многих учеников при их изучении и при подготовке к экзамену по физике.

    """)


# Названия разделов в меню задаём здесь, а не именами файлов: так они по-русски
# и не зависят от того, как называется сам файл.
pages = [
    st.Page(home, title="Главная", default=True),
    st.Page("pages/01_Mechanics.py", title="Механика"),
    st.Page("pages/02_Optics.py", title="Оптика"),
    st.Page("pages/03_Magnetism.py", title="Магнетизм"),
]

st.navigation(pages).run()
